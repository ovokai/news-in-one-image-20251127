# Typographic characters the copy may contain, folded onto plain glyphs.
ALIASES = {
    '–': '-', '—': '-', '−': '-',
    '‘': "'", '’': "'", '‚': "'",
    '“': '"', '”': '"',
    '·': '•', '…': '.',
}

# Hollow box, drawn for any character with no glyph of its own.
FALLBACK = (0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F)


def glyph_for(ch):
    """Return the 7 row masks for one character."""
    if ch in FONT:
        return FONT[ch]
    if ch in ALIASES:
        return FONT[ALIASES[ch]]
    return FALLBACK
